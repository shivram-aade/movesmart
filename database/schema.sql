DROP DATABASE IF EXISTS transit;
CREATE DATABASE transit;
USE transit;

CREATE TABLE stops (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, lat DOUBLE NOT NULL, lng DOUBLE NOT NULL);
CREATE TABLE routes (id INT AUTO_INCREMENT PRIMARY KEY, number VARCHAR(10) NOT NULL, name VARCHAR(120) NOT NULL);
CREATE TABLE route_stops (route_id INT NOT NULL, stop_id INT NOT NULL, seq INT NOT NULL, offset_min INT NOT NULL,
  PRIMARY KEY (route_id, seq), FOREIGN KEY (route_id) REFERENCES routes(id), FOREIGN KEY (stop_id) REFERENCES stops(id));
CREATE TABLE buses (id INT AUTO_INCREMENT PRIMARY KEY, route_id INT NOT NULL, plate VARCHAR(20) NOT NULL,
  total_seats INT NOT NULL DEFAULT 40, occupied INT NOT NULL DEFAULT 0, lat DOUBLE, lng DOUBLE, speed_kmph DOUBLE DEFAULT 25,
  next_seq INT NOT NULL DEFAULT 2, delay_min INT NOT NULL DEFAULT 0, FOREIGN KEY (route_id) REFERENCES routes(id));

CREATE TABLE users (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL, email VARCHAR(120) NOT NULL UNIQUE,
  mobile VARCHAR(20) UNIQUE, password_hash VARCHAR(100) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE favorites (id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, from_stop INT NOT NULL, to_stop INT NOT NULL,
  UNIQUE KEY uq (user_id, from_stop, to_stop), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (from_stop) REFERENCES stops(id), FOREIGN KEY (to_stop) REFERENCES stops(id));
CREATE TABLE search_history (user_id INT NOT NULL, from_stop INT NOT NULL, to_stop INT NOT NULL,
  searched_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (user_id, from_stop, to_stop),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (from_stop) REFERENCES stops(id), FOREIGN KEY (to_stop) REFERENCES stops(id));
CREATE TABLE notifications (id INT AUTO_INCREMENT PRIMARY KEY, type VARCHAR(20) NOT NULL, message VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE notif_reads (user_id INT NOT NULL, notification_id INT NOT NULL, PRIMARY KEY (user_id, notification_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY (notification_id) REFERENCES notifications(id) ON DELETE CASCADE);
CREATE TABLE resets (token_hash CHAR(64) PRIMARY KEY, user_id INT NOT NULL, expires_at DATETIME NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);

